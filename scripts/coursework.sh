#!/bin/sh
set -eu

usage() {
  printf '%s\n' 'Usage: sh scripts/coursework.sh materialize COURSE' \
    '       sh scripts/coursework.sh shell COURSE [--web] [-- COMMAND ...]'
}

case ${1-} in
  -h|--help) usage; exit 0 ;;
  materialize|shell) action=$1; shift ;;
  *) usage >&2; exit 2 ;;
esac
[ "$#" -ge 1 ] || { usage >&2; exit 2; }
course=$1
shift
case $course in
  ''|[!a-zA-Z0-9]*|*[!a-zA-Z0-9_-]*) printf 'Invalid course name: %s\n' "$course" >&2; exit 2 ;;
esac
if [ "$action" = materialize ] && [ "$#" -ne 0 ]; then usage >&2; exit 2; fi

root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd -P)
templates=$root/coursework-tools
project=$root/coursework/$course
if [ -L "$project" ] || [ ! -f "$project/workflow.just" ]; then
  printf 'No coursework workflow for %s.\n' "$course" >&2
  exit 1
fi

# Tool pins for coursework runtimes and verifier dependencies.
node='node = "24.13.0"'
python='python = "3.13.18"'
uv='uv = "0.13.5"'
case $course in
  B1-1) tools=$(printf '%s\n' "$node" "$python") ;;
  B1-2) tools=$(printf '%s\n' "$node" 'java = "temurin-21.0.10+7.0.LTS"') ;;
  B2-1|B3-2|B5-1) tools=$python ;;
  B2-2) tools=$node ;;
  B3-1) tools=$(printf '%s\n' "$python" 'terraform = "1.16.5"') ;;
  B4-1|B4-2) tools= ;;
  B5-2) tools=$(printf '%s\n' "$python" "$uv") ;;
  B6-1) tools='"conda:sqlite" = "3.49.2"' ;;
  B6-2) tools=$(printf '%s\n' "$python" "$uv" "$node") ;;
  B6-3) tools=$(printf '%s\n' "$python" "$uv" "$node" 'pnpm = "12.10.1"') ;;
  *) printf 'No toolchain profile for %s.\n' "$course" >&2; exit 1 ;;
esac

cd "$project"
marker='# Generated by scripts/coursework.sh; do not edit.'
for path in justfile mise.toml .coursework-dev; do
  if [ -n "$(git ls-files -- "$path")" ]; then
    printf 'Refusing to replace tracked path: %s/%s\n' "$course" "$path" >&2
    exit 1
  fi
done
if [ -L .coursework-dev ] || { [ -e .coursework-dev ] && [ ! -d .coursework-dev ]; }; then
  printf 'Not a generated directory: %s/.coursework-dev\n' "$course" >&2
  exit 1
fi
files='justfile mise.toml .coursework-dev/Dockerfile .coursework-dev/Dockerfile.dockerignore .coursework-dev/shell.sh'
for path in $files; do
  if [ -L "$path" ] || { [ -e "$path" ] && { [ ! -f "$path" ] || [ "$(head -n 1 "$path")" != "$marker" ]; }; }; then
    printf 'Refusing to replace non-generated file: %s/%s\n' "$course" "$path" >&2
    exit 1
  fi
done

stage=$(mktemp -d .coursework-stage.XXXXXX)
trap 'rm -rf "$stage"' EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM
mkdir "$stage/.coursework-dev"
for template in justfile .coursework-dev/Dockerfile .coursework-dev/shell.sh; do
  { printf '%s\n' "$marker"; cat "$templates/${template##*/}"; } >"$stage/$template"
done
{
  printf '%s\n' "$marker" '[tools]' 'just = "1.43.1"' "$tools"
  cat "$templates/mise.toml"
} >"$stage/mise.toml"

# Docker gets tracked coursework inputs, plus exactly the generated build inputs.
# Fail closed on names that cannot be represented literally as Docker ignore patterns.
git -c core.quotePath=false ls-files --deduplicate >"$stage/tracked"
{
  printf '%s\n' "$marker" '**'
  while IFS= read -r path; do
    case $path in
      ''|*[!a-zA-Z0-9_./@+-]*) printf 'Unsupported Docker context path: %s\n' "$path" >&2; exit 1 ;;
    esac
    printf '!%s\n' "$path"
  done <"$stage/tracked"
  printf '%s\n' '!mise.toml' '!justfile'
  cat "$templates/context-exclusions"
} >"$stage/.coursework-dev/Dockerfile.dockerignore"

mkdir -p .coursework-dev
for path in $files; do
  mv -f "$stage/$path" "$path"
done
case $action in
  materialize) printf 'Materialized %s. From the course directory: mise run setup; mise exec -- just\n' "$course" ;;
  shell) sh .coursework-dev/shell.sh "$@" ;;
esac
