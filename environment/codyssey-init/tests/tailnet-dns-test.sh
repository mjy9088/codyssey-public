#!/usr/bin/env bash
set -euo pipefail
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
mkdir "$work/bin"
cat > "$work/bin/tailscale" <<'EOF'
#!/bin/sh
cat "$DNS_TEST_STATUS"
EOF
chmod 0755 "$work/bin/tailscale"
export PATH="$work/bin:$PATH" DNS_TEST_STATUS="$work/status.json"
export CODYSSEY_RESOLV_CONF="$work/resolv.conf" CODYSSEY_RESOLV_BASE="$work/base"
printf 'nameserver 192.0.2.53\noptions timeout:2 ndots:0 attempts:3\n' > "$work/base"
cp "$work/base" "$work/resolv.conf"
inode=$(stat -c '%i' "$work/resolv.conf")
printf '{"BackendState":"Running","CurrentTailnet":{"MagicDNSSuffix":"tailnet.example.invalid"}}\n' > "$work/status.json"
bash /src/scripts/tailnet-dns.sh
[[ $(stat -c '%i' "$work/resolv.conf") == "$inode" ]]
grep -qx 'search tailnet.example.invalid' "$work/resolv.conf"
grep -qx 'nameserver 100.100.100.100' "$work/resolv.conf"
grep -qx 'options timeout:2 attempts:3 ndots:1' "$work/resolv.conf"
grep -q 'generated by tailscale' "$work/resolv.conf"
cp "$work/resolv.conf" "$work/expected"
bash /src/scripts/tailnet-dns.sh
cmp "$work/resolv.conf" "$work/expected"
printf '{"BackendState":"Running","CurrentTailnet":{"MagicDNSSuffix":"invalid\\nsearch injected"}}\n' > "$work/status.json"
if bash /src/scripts/tailnet-dns.sh; then exit 1; fi
cmp "$work/resolv.conf" "$work/expected"
printf '{"BackendState":"NeedsLogin"}\n' > "$work/status.json"
bash /src/scripts/tailnet-dns.sh
cmp "$work/resolv.conf" "$work/base"
printf 'PASS: container DNS search priority, mount preservation, idempotence, validation and restoration.\n'
