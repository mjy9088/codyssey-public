#!/usr/bin/env bash
# Docker owns the resolv.conf mount, so update it in place, never via rename.
set -euo pipefail
status=$(tailscale status --json) || exit 0
conf=${CODYSSEY_RESOLV_CONF:-/etc/resolv.conf}
base=${CODYSSEY_RESOLV_BASE:-/var/run/tailscale/resolv.conf.base}
if [[ $(jq -er '.BackendState' <<< "$status") != Running ]]; then
  if [[ -f $base ]] && ! cmp -s "$base" "$conf"; then cat "$base" > "$conf"; fi
  exit 0
fi
suffix=$(jq -er '.CurrentTailnet.MagicDNSSuffix // empty' <<< "$status") || exit 0
suffix=${suffix%.}
[[ ${#suffix} -le 253 && $suffix =~ ^[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$ ]] || {
  printf 'Invalid MagicDNS search domain; resolver left unchanged.\n' >&2; exit 1;
}
# Docker commonly sets ndots:0, which queries bare names before the search
# domain and can return a Docker hostname instead of its tailnet address.
options=$(awk '$1 == "options" {for (i=2; i<=NF; i++) if ($i !~ /^ndots:/) printf "%s ", $i} END {print "ndots:1"}' "$conf")
desired=$(printf '# resolv.conf(5) file generated by tailscale\nsearch %s\nnameserver 100.100.100.100\noptions %s\n' "$suffix" "$options")
[[ $(cat "$conf") != "$desired" ]] || exit 0
printf '%s\n' "$desired" > "$conf"
